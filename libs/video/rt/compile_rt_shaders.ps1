# Offline DXC build of the RTAO compute shaders into rsx_rt_ao_dxil.h (one byte array per entry point).
# Needs dxc.exe + dxil.dll (Windows SDK 10.0.26100 bin\x64). The game ships only the resulting bytecode.
param([string]$Dxc = 'C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\dxc.exe')
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$src = Join-Path $here 'rsx_rt_ao.hlsl'
$out = Join-Path $here '..\rsx_rt_ao_dxil.h'
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('/* Generated by rt/compile_rt_shaders.ps1 from rt/rsx_rt_ao.hlsl (dxc, cs_6_5). Do not edit. */')
foreach ($e in 'cs_trace','cs_temporal','cs_blur_h','cs_up') {
    $tmp = Join-Path $env:TEMP "$e.dxil"
    & $Dxc -nologo -T cs_6_5 -E $e -O3 -Fo $tmp $src
    if ($LASTEXITCODE -ne 0) { throw "dxc failed for $e" }
    $b = [IO.File]::ReadAllBytes($tmp)
    [void]$sb.AppendLine("static const unsigned char k_${e}_dxil[$($b.Length)] = {")
    for ($i = 0; $i -lt $b.Length; $i += 24) {
        $n = [Math]::Min(24, $b.Length - $i)
        [void]$sb.AppendLine('  ' + (($b[$i..($i+$n-1)] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ',') + ',')
    }
    [void]$sb.AppendLine('};')
}
[IO.File]::WriteAllText($out, $sb.ToString())
Write-Host "wrote $out"
